const INDEX = new Map(PLACE_ORDER.map((id, i) => [id, i]));

/** Distance routière réelle (km, 1 décimale) — `null` si paire inconnue. */
export function roadDistanceKm(fromId: string, toId: string): number | null {
  const i = INDEX.get(fromId);
  const j = INDEX.get(toId);
  if (i === undefined || j === undefined || i === j) return null;
  return Math.round((ROAD_M[i]![j]! / 1000) * 10) / 10;
}
